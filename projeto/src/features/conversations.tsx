type LinkRecord = ReturnType<typeof connectService.professionalLinks>[number];
const dateLabel = (timestamp: number) =>
  new Date(timestamp).toLocaleString('pt-BR', { dateStyle: 'short', timeStyle: 'short' });
const failure = (error: unknown) =>
  error instanceof Error ? error.message : 'Não foi possível abrir a conversa. Tente novamente.';

function AttachmentView({ actor, message }: { actor: string; message: ChatMessage }) {
  const [url, setUrl] = useState('');
  const [error, setError] = useState('');
  const [request, setRequest] = useState(0);
  const attachment = message.attachment!;
  const expired = Boolean(attachment.expired);
  useEffect(() => {
    if (!request || expired) return;
    let active = true;
    let objectURL: string | undefined;
    void messagingService
      .media(actor, message.thread, message.id)
      .then((blob) => {
        if (!active) return;
        objectURL = URL.createObjectURL(blob);
        setUrl(objectURL);
      })
      .catch((reason) => {
        if (active) setError(failure(reason));
      });
    return () => {
      active = false;
      if (objectURL) URL.revokeObjectURL(objectURL);
    };
  }, [actor, message.id, message.thread, expired, request]);
  if (expired) return <p>Vídeo expirado</p>;
  const label = { audio: 'áudio', image: 'foto', video: 'vídeo' }[attachment.kind];
  return (
    <div className="grid gap-1.5">
      {url ? (
        attachment.kind === 'image' ? (
          // Blob URLs are generated by IndexedDB in the offline distribution.
          // eslint-disable-next-line @next/next/no-img-element
          <img
            className="max-h-72 max-w-full rounded-lg object-contain"
            src={url}
            alt={'Foto anexada: ' + attachment.name}
          />
        ) : attachment.kind === 'video' ? (
          <video
            className="max-h-72 max-w-full rounded-lg"
            src={url}
            controls
            playsInline
            preload="metadata"
            aria-label={'Vídeo: ' + attachment.name}
          />
        ) : (
          <audio
            className="max-w-full"
            src={url}
            controls
            preload="metadata"
            aria-label={'Áudio: ' + attachment.name}
          />
        )
      ) : (
        <Button
          variant="outline"
          size="sm"
          className="justify-self-start"
          disabled={!!request && !error}
          onClick={() => {
            setError('');
            setRequest(request + 1);
          }}
        >
          Abrir {label}
        </Button>
      )}
      <small className="break-all">
        {attachment.name} · {Math.ceil(attachment.size / 1024)} KB
      </small>
      {attachment.expiresAt && <small>Disponível até {dateLabel(attachment.expiresAt)}</small>}
      {error && <p role="alert">{error}</p>}
    </div>
  );
}

function Thread({
  actor,
  link,
  otherName,
  back,
  revision,
}: {
  actor: string;
  link: LinkRecord;
  otherName: string;
  back: () => void;
  revision: number;
}) {
  const [items, setItems] = useState<ChatMessage[]>([]);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState('');
  const [retry, setRetry] = useState(0);
  const [query, setQuery] = useState('');
  const [shown, setShown] = useState(30);
  const [text, setText] = useState('');
  const [file, setFile] = useState<File>();
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  const [sent, setSent] = useState('');
  const sending = useRef(false);
  const fileInput = useRef<HTMLInputElement>(null);
  const log = useRef<HTMLOListElement>(null);
  const pinBottom = useRef(true);
  const writable =
    link.endedAt === null && linkAllows(link.trainerId, link.studentId, 'chat', link.startedAt);
  useEffect(() => {
    let active = true;
    async function refresh() {
      try {
        const received = await messagingService.messages(actor, link.id);
        if (!active) return;
        setItems(received);
        setLoadError('');
        if (
          document.visibilityState === 'visible' &&
          received.some((item) => item.recipient === actor && item.readAt === undefined)
        )
          await messagingService.markRead(actor, link.id);
      } catch (reason) {
        if (active) setLoadError(failure(reason));
      } finally {
        if (active) setLoading(false);
      }
    }
    void refresh();
    document.addEventListener('visibilitychange', refresh);
    return () => {
      active = false;
      document.removeEventListener('visibilitychange', refresh);
    };
  }, [actor, link.id, revision, retry]);
  useEffect(() => {
    if (log.current && pinBottom.current && !query)
      log.current.scrollTop = log.current.scrollHeight;
  }, [items, query]);
  async function submit(event: FormEvent) {
    event.preventDefault();
    if (sending.current) return;
    sending.current = true;
    setBusy(true);
    setError('');
    setSent('');
    try {
      await messagingService.send(actor, link.id, text, file);
      setText('');
      setFile(undefined);
      setQuery('');
      setShown(30);
      if (fileInput.current) fileInput.current.value = '';
      pinBottom.current = true;
      setSent('Mensagem salva neste navegador.');
    } catch (reason) {
      setError(failure(reason));
    } finally {
      sending.current = false;
      setBusy(false);
    }
  }
  const term = query.trim().toLocaleLowerCase('pt-BR');
  const found = items.filter(
    (item) =>
      !term ||
      [item.text, item.attachment?.name, item.attachment?.expired && 'Vídeo expirado'].some(
        (part) => typeof part === 'string' && part.toLocaleLowerCase('pt-BR').includes(term),
      ),
  );
  return (
    <Panel
      title={otherName}
      description={writable ? 'Conversa do acompanhamento' : 'Histórico disponível para consulta'}
      action={
        <Button type="button" size="sm" variant="ghost" onClick={back}>
          <ArrowLeft aria-hidden /> Conversas
        </Button>
      }
    >
      <div className="grid gap-4">
        <label className="flex items-center gap-2">
          <Search size={17} aria-hidden />
          <Input
            type="search"
            aria-label="Buscar no histórico"
            placeholder="Buscar no histórico"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
          />
        </label>
        {loadError ? (
          <div>
            <Feedback error={loadError} />
            <Button variant="outline" onClick={() => setRetry(retry + 1)}>
              Tentar novamente
            </Button>
          </div>
        ) : loading ? (
          <p role="status">Abrindo histórico…</p>
        ) : found.length ? (
          <>
            {found.length > shown && (
              <Button variant="outline" onClick={() => setShown(shown + 30)}>
                Mostrar mensagens anteriores
              </Button>
            )}
            <ol
              ref={log}
              aria-label="Histórico da conversa"
              tabIndex={0}
              onScroll={(event) => {
                const el = event.currentTarget;
                pinBottom.current = el.scrollHeight - el.scrollTop - el.clientHeight < 50;
              }}
              className="flex max-h-[46dvh] min-h-28 flex-col gap-3 overflow-y-auto p-1"
            >
              {found.slice(-shown).map((item) => (
                <li
                  key={item.id}
                  className={
                    'grid max-w-[92%] gap-2 rounded-2xl border border-border px-4 py-3 ' +
                    (item.sender === actor ? 'self-end bg-secondary' : 'self-start bg-background')
                  }
                >
                  <strong className="text-xs">{item.sender === actor ? 'Você' : otherName}</strong>
                  {item.text && (
                    <p className="whitespace-pre-wrap break-words [overflow-wrap:anywhere]">
                      {item.text}
                    </p>
                  )}
                  {item.attachment && <AttachmentView message={item} actor={actor} />}
                  <small className="text-muted-foreground">
                    {dateLabel(item.createdAt)}
                    {item.sender === actor &&
                      (item.readAt === undefined ? ' · Salva aqui' : ' · Lida aqui')}
                  </small>
                </li>
              ))}
            </ol>
          </>
        ) : (
          <p className="py-6 text-muted-foreground">
            {term
              ? 'Nenhuma mensagem encontrada para esta busca.'
              : 'O histórico começa com a primeira mensagem.'}
          </p>
        )}
        {writable ? (
          <form onSubmit={submit} className="grid gap-2 border-t border-border pt-4">
            <label htmlFor="chat-message">Sua mensagem para {otherName}</label>
            <Textarea
              id="chat-message"
              value={text}
              maxLength={MAX_MESSAGE_LENGTH}
              disabled={busy}
              onChange={(e) => {
                setText(e.target.value);
                setSent('');
              }}
              placeholder="Escreva uma mensagem…"
              rows={2}
            />
            <div className="flex flex-wrap items-center justify-between gap-2">
              <Button
                type="button"
                variant="outline"
                disabled={busy}
                onClick={() => fileInput.current?.click()}
              >
                <Paperclip aria-hidden /> Anexar arquivo
              </Button>
              <input
                type="file"
                ref={fileInput}
                hidden
                aria-label="Foto, áudio ou vídeo"
                accept={acceptedMedia}
                onChange={(e) => {
                  setFile(e.target.files?.[0]);
                  setSent('');
                  setError('');
                }}
              />
              <Button disabled={busy || (!text.trim() && !file)}>
                <Send aria-hidden />
                {busy ? 'Salvando…' : 'Enviar mensagem'}
              </Button>
            </div>
            {file && (
              <div className="flex flex-wrap items-center gap-2 text-sm">
                <span className="break-all">{file.name}</span>
                <Button
                  type="button"
                  size="sm"
                  variant="ghost"
                  disabled={busy}
                  onClick={() => {
                    setFile(undefined);
                    if (fileInput.current) fileInput.current.value = '';
                  }}
                >
                  Remover anexo
                </Button>
              </div>
            )}
            <small className="text-muted-foreground">
              Foto até 5 MB, áudio até 8 MB e vídeo até 20 MB. Vídeos ficam disponíveis por sete
              dias.
            </small>
            <Feedback error={error} success={sent} />
          </form>
        ) : (
          <p className="border-t border-border pt-4 text-sm">
            {link.endedAt === null
              ? 'O serviço atual permite consultar o histórico. O envio está desativado.'
              : 'Acompanhamento encerrado. Você pode consultar as mensagens anteriores.'}
          </p>
        )}
      </div>
    </Panel>
  );
}

function Inbox({ account }: { account: ConnectAccount }) {
  useSyncExternalStore(connectService.subscribe, connectService.revision, () => 0);
  useSyncExternalStore(marketplaceService.subscribe, marketplaceService.revision, () => 0);
  const revision = useSyncExternalStore(
    messagingService.subscribe,
    messagingService.revision,
    () => 0,
  );
  const links = connectService.professionalLinks(account.id);
  const [selected, select] = useState('');
  const [counts, setCounts] = useState<Record<string, number>>({});
  const [loadError, setLoadError] = useState('');
  const [retry, setRetry] = useState(0);
  const selectedLink = links.find((link) => link.id === selected);
  useEffect(() => {
    let active = true;
    void messagingService
      .unread(account.id)
      .then((next) => {
        if (active) {
          setCounts(next);
          setLoadError('');
        }
      })
      .catch((error) => {
        if (active) setLoadError(failure(error));
      });
    return () => {
      active = false;
    };
  }, [account.id, revision, retry]);
  const other = (link: LinkRecord) =>
    connectService.getAccount(account.role === 'aluno' ? link.trainerId : link.studentId)?.name ??
    'Participante';
  if (!links.length)
    return (
      <Panel>
        <EmptyState
          title="Sua primeira conversa"
          description={
            account.role === 'aluno'
              ? 'Conecte-se a um personal para abrir o histórico do acompanhamento.'
              : 'A conversa aparece quando um aluno aceita seu convite ou você aprova um vínculo.'
          }
          action={
            <Button variant="outline" asChild>
              <Link href={account.role === 'aluno' ? '/aluno/personal' : '/personal'}>
                {account.role === 'aluno' ? 'Meu personal' : 'Convidar alunos'}
              </Link>
            </Button>
          }
        />
      </Panel>
    );
  return (
    <div className="grid items-start gap-4 lg:grid-cols-[minmax(15rem,1fr)_minmax(0,2fr)]">
      <div className={selectedLink ? 'hidden lg:block' : ''}>
        <Panel title="Acompanhamentos">
          {loadError && (
            <div>
              <Feedback error={loadError} />
              <Button variant="ghost" onClick={() => setRetry(retry + 1)}>
                Tentar novamente
              </Button>
            </div>
          )}
          <ul className="grid gap-1">
            {[...links]
              .sort((a, b) => b.startedAt - a.startedAt)
              .map((link) => (
                <li key={link.id}>
                  <button
                    className={
                      'flex w-full items-center gap-3 rounded-lg px-2 py-3 text-left hover:bg-secondary ' +
                      (selected === link.id ? 'bg-secondary' : '')
                    }
                    aria-pressed={selected === link.id}
                    onClick={() => select(link.id)}
                  >
                    <Avatar name={other(link)} small />
                    <span className="grid min-w-0 flex-1">
                      <strong className="break-words">{other(link)}</strong>
                      <small className="text-muted-foreground">
                        {link.endedAt === null ? 'Em acompanhamento' : 'Encerrado'} ·{' '}
                        {new Date(link.startedAt).toLocaleDateString('pt-BR')}
                      </small>
                    </span>
                    {counts[link.id] > 0 && (
                      <span className="rounded-full bg-primary px-2 py-1 text-xs text-primary-foreground">
                        {counts[link.id]} {counts[link.id] === 1 ? 'não lida' : 'não lidas'}
                      </span>
                    )}
                    <ChevronRight size={16} aria-hidden />
                  </button>
                </li>
              ))}
          </ul>
        </Panel>
      </div>
      {selectedLink ? (
        <Thread
          key={selectedLink.id}
          actor={account.id}
          link={selectedLink}
          otherName={other(selectedLink)}
          back={() => select('')}
          revision={revision}
        />
      ) : (
        <div className="hidden lg:block">
          <Panel>
            <div className="grid justify-items-center gap-3 py-14 text-center">
              <MessageCircle aria-hidden />
              <p>Selecione um acompanhamento para abrir a conversa.</p>
            </div>
          </Panel>
        </div>
      )}
    </div>
  );
}
